#!/usr/bin/env node
// 同步 AA 综合智能指数；页面仍然完全离线。
// AA_API_KEY=… node scripts/sync-rankings.mjs
// 无 Key 时使用 OpenRouter 转发的同名指数，并在快照中注明渠道。
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { buildIntelligenceRankings, loadOfficial, loadOpenRouter } from './aa-rankings.mjs';
import { loadFrontend } from './frontend-rankings.mjs';

const page = new URL('../page/', import.meta.url);
const dryRun = process.argv.includes('--dry-run');
async function fetchJson(url, headers = {}) {
  const response = await fetch(url, { headers, signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`榜单接口请求失败（HTTP ${response.status}），保留现有快照。`);
  return response.json();
}
async function main() {
  // 本地 Key 不进入版本控制或插件包；已有环境变量优先。
  try {
    process.loadEnvFile(fileURLToPath(new URL('../.env', import.meta.url)));
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const source = await readFile(new URL('catalog.js', page), 'utf8');
  const line = source.split('\n').find((s) => s.startsWith('export const CATALOG = '));
  if (!line) throw new Error('目录缺少 CATALOG。');
  const catalog = JSON.parse(line.slice('export const CATALOG = '.length).replace(/;$/, ''));
  const key = process.env.AA_API_KEY || process.env.ARTIFICIAL_ANALYSIS_API_KEY;
  // 已配置官方 Key 时，认证或网络失败直接报错，不静默切换渠道。
  if (!key) console.warn('未配置 AA_API_KEY：使用 OpenRouter 转发的 AA Intelligence Index；转发源未提供指数版本与评测日期。');
  const fetchedAt = new Date().toISOString();
  const [loaded, frontend] = await Promise.all([
    key ? loadOfficial(fetchJson, key) : loadOpenRouter(fetchJson),
    loadFrontend(fetchJson, catalog, fetchedAt),
  ]);
  const { rankings, skipped } = buildIntelligenceRankings(loaded.records, catalog, { ...loaded, fetchedAt });
  rankings.tasks.frontend = frontend.task;
  rankings.sources['design-arena-website'] = frontend.source;
  console.log(`前端 / 网页：${frontend.task.models.length} 个模型；Design Arena Website Elo（OpenRouter 转发）。`);
  console.log(`综合能力：${rankings.tasks.intelligence.models.length} 个模型；渠道 ${loaded.channel}；指数版本 ${loaded.version ?? '未提供'}。`);
  if (skipped.length) console.log(`未匹配目录的型号：${skipped.join('、')}`);
  if (dryRun) { console.log('未写入（--dry-run）。'); return; }
  await writeFile(new URL('rankings.js', page), `// Generated by scripts/sync-rankings.mjs. AA raw scores; date is fetch date.\nexport const RANKINGS = ${JSON.stringify(rankings)};\n`);
  console.log(`已更新 ${fileURLToPath(new URL('rankings.js', page))}。`);
}
main().catch((error) => { console.error(error.message); process.exitCode = 1; });
