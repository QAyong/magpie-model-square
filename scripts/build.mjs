#!/usr/bin/env bun
// 将页面与离线数据合成经典脚本，兼容不带 allow-same-origin 的页面沙盒。
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const result = await Bun.build({
  entrypoints: [fileURLToPath(new URL('page/app.js', root))],
  target: 'browser', format: 'esm', splitting: false, minify: false,
});
if (!result.success) throw new AggregateError(result.logs, '页面打包失败');
const code = await result.outputs[0].text();
// ESM bundle 已将静态与动态 import 全部内联；异步启动保留榜单的初始化顺序。
const inputs = ['app.js', 'view.js', 'catalog.js', 'prices.js', 'currency.js', 'icon-index.js', 'rankings.js', 'mono-icons.js',
  ...(await readdir(new URL('page/icons/', root))).filter((name) => name.endsWith('.svg')).sort().map((name) => `icons/${name}`)];
const hash = createHash('sha256');
for (const file of inputs) hash.update(await readFile(new URL(`page/${file}`, root)));
const output = `// Generated by scripts/build.mjs. Do not edit.\n// Sources SHA256: ${hash.digest('hex')}\n(async () => {\n${code}\n})().catch((error) => {\n  console.error('模型广场启动失败', error);\n  const empty = document.querySelector('#empty-state');\n  if (empty) {\n    empty.hidden = false;\n    empty.textContent = '页面未能启动，请更新插件后重新打开。';\n  }\n});\n`;
await writeFile(new URL('page/app.bundle.js', root), output);
console.error(`已打包页面与离线数据：${Buffer.byteLength(output)} 字节。`);
